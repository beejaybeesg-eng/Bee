import {readFileSync, writeFileSync} from 'fs';
import {geoPath, geoAlbersUsa, geoNaturalEarth1} from 'd3-geo';
import * as topo from 'topojson-client';
import {presimplify, simplify} from 'topojson-simplify';
const r = p => p.replace(/(\d+)\.\d+/g,'$1');
let us = JSON.parse(readFileSync('node_modules/us-atlas/states-albers-10m.json'));
us = simplify(presimplify(us), 0.6);
const states = topo.feature(us, us.objects.states).features.map(f=>({id:f.id,name:f.properties.name,d:r(geoPath()(f))}));
const nationMesh = r(geoPath()(topo.mesh(us, us.objects.nation)));
const w = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json'));
const land = topo.feature(w, w.objects.land);
const W=975,H=610;
const atl = geoNaturalEarth1().fitExtent([[0,0],[W,H]],{type:'MultiPoint',coordinates:[[-100,48],[28,-22],[-100,-22],[28,48]]});
const landD = r(geoPath(atl)(land));
const grat=[];
const usP = geoAlbersUsa().scale(1300).translate([487.5,305]);
const proj = {us:([lon,lat])=>{const p=usP([lon,lat]);return p&&p.map(v=>+v.toFixed(1))}, atl:([lon,lat])=>atl([lon,lat]).map(v=>+v.toFixed(1))};
const pts = JSON.parse(readFileSync('points.json'));
const out={};
for(const [id,[lon,lat]] of Object.entries(pts)) out[id]={us:proj.us([lon,lat]),atl:proj.atl([lon,lat])};
writeFileSync('map.json', JSON.stringify({states,nation:nationMesh,land:landD,pts:out}));
console.log('states',states.length,'size',JSON.stringify({states,landD}).length);
